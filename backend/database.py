
from dotenv import load_dotenv

load_dotenv()

import os
import psycopg
from psycopg.rows import dict_row

DATABASE_URL = os.getenv("DATABASE_URL")

if not DATABASE_URL:
    raise RuntimeError(
        "DATABASE_URL is not configured. "
        "Add your Neon connection string to Render Environment."
    )


def get_connection():
    return psycopg.connect(
        DATABASE_URL,
        row_factory=dict_row,
        connect_timeout=10
    )


def init_db():
    with get_connection() as connection:
        with connection.cursor() as cursor:

            # ---------------- USERS ----------------

            cursor.execute("""
                CREATE TABLE IF NOT EXISTS users (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    username TEXT UNIQUE NOT NULL,
                    email TEXT UNIQUE NOT NULL,
                    password_hash TEXT NOT NULL,
                    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                    signing_public_key TEXT,
                    signing_private_key_encrypted BYTEA
                )
            """)

            cursor.execute("""
                ALTER TABLE users
                ADD COLUMN IF NOT EXISTS signing_public_key TEXT
            """)

            cursor.execute("""
                ALTER TABLE users
                ADD COLUMN IF NOT EXISTS signing_private_key_encrypted BYTEA
            """)

            # ---------------- PASSWORD RESET ----------------

            cursor.execute("""
                CREATE TABLE IF NOT EXISTS password_reset_tokens (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id BIGINT NOT NULL REFERENCES users(id),
                    token_hash TEXT UNIQUE NOT NULL,
                    expires_at TIMESTAMP NOT NULL,
                    used INTEGER DEFAULT 0
                )
            """)

            # ---------------- MESSAGES ----------------

            cursor.execute("""
                CREATE TABLE IF NOT EXISTS messages (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    sender_id BIGINT NOT NULL REFERENCES users(id),
                    recipient_id BIGINT NOT NULL REFERENCES users(id),
                    ciphertext TEXT NOT NULL,
                    signature TEXT,
                    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                    read_at TIMESTAMP,
                    sender_public_key TEXT,
                    sender_deleted_at TIMESTAMP,
                    recipient_deleted_at TIMESTAMP
                )
            """)

            # Safe migrations for existing messages table

            cursor.execute("""
                ALTER TABLE messages
                ADD COLUMN IF NOT EXISTS sender_public_key TEXT
            """)

            cursor.execute("""
                ALTER TABLE messages
                ADD COLUMN IF NOT EXISTS sender_deleted_at TIMESTAMP
            """)

            cursor.execute("""
                ALTER TABLE messages
                ADD COLUMN IF NOT EXISTS recipient_deleted_at TIMESTAMP
            """)

            # ---------------- ENCRYPTED FILES ----------------

            cursor.execute("""
                CREATE TABLE IF NOT EXISTS encrypted_files (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id BIGINT NOT NULL REFERENCES users(id),
                    original_filename TEXT NOT NULL,
                    content_type TEXT NOT NULL,
                    encrypted_data BYTEA NOT NULL,
                    encryption_iv BYTEA NOT NULL,
                    file_hash TEXT NOT NULL,
                    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                    signature TEXT,
                    signing_public_key TEXT
                )
            """)

            cursor.execute("""
                ALTER TABLE encrypted_files
                ADD COLUMN IF NOT EXISTS signature TEXT
            """)

            cursor.execute("""
                ALTER TABLE encrypted_files
                ADD COLUMN IF NOT EXISTS signing_public_key TEXT
            """)

            # ---------------- FILE SHARING ----------------

            cursor.execute("""
                CREATE TABLE IF NOT EXISTS file_shares (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    file_id BIGINT NOT NULL
                        REFERENCES encrypted_files(id) ON DELETE CASCADE,
                    sender_id BIGINT NOT NULL
                        REFERENCES users(id) ON DELETE CASCADE,
                    recipient_id BIGINT NOT NULL
                        REFERENCES users(id) ON DELETE CASCADE,
                    shared_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                    UNIQUE (file_id, recipient_id)
                )
            """)

            # ---------------- INDEXES ----------------

            cursor.execute("""
                CREATE INDEX IF NOT EXISTS idx_messages_recipient
                ON messages(recipient_id, created_at DESC)
            """)

            cursor.execute("""
                CREATE INDEX IF NOT EXISTS idx_messages_sender
                ON messages(sender_id)
            """)

            cursor.execute("""
                CREATE INDEX IF NOT EXISTS idx_encrypted_files_user
                ON encrypted_files(user_id)
            """)

            cursor.execute("""
                CREATE INDEX IF NOT EXISTS idx_file_shares_recipient
                ON file_shares(recipient_id)
            """)


if __name__ == "__main__":
    init_db()
    print("CryptoVault database initialized successfully!")
